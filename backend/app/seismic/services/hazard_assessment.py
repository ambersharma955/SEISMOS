DISCLAIMER=("PRELIMINARY SCREENING ONLY. Generated by simple rule-based heuristics from USGS earthquake parameters and coarse terrain data. Not an official warning. Follow official tsunami and disaster-management agencies (e.g. INCOIS, PTWC, NDMA).")
_OFFSHORE_RE=re.compile(r"\b(off|offshore|sea|ocean|strait|gulf|trench|ridge|rise|channel|bay of|fracture zone)\b",re.I)
def infer_offshore(ev,terrain=None):
 if _OFFSHORE_RE.search(ev.location or ""): return True
 if terrain is not None: return terrain.epicenter_elevation_m<=0
 return None
def screen_tsunami(ev,offshore):
 m,d=ev.magnitude,ev.depth_km; factors=[]; score=0
 pts=5 if m>=8 else 4 if m>=7.5 else 3 if m>=7 else 2 if m>=6.5 else 0; score+=pts
 if pts: factors.append(f"Magnitude {m:.1f} is large enough to displace the seafloor (+{pts})")
 if d<=35: score+=2; factors.append(f"Shallow focus ({d:.0f} km) transfers more energy to the seafloor (+2)")
 elif d<=70: score+=1; factors.append(f"Moderately shallow focus ({d:.0f} km) (+1)")
 elif d>100: score-=3; factors.append(f"Deep focus ({d:.0f} km) makes tsunami generation unlikely (-3)")
 if offshore is True: score+=2; factors.append("Epicentre appears to be offshore / under the sea (+2)")
 elif offshore is False: score-=2; factors.append("Epicentre appears to be on land (-2)")
 else: factors.append("Offshore vs onshore location unknown")
 if ev.usgs_tsunami_flag: score+=1; factors.append("USGS has flagged this event for tsunami information (+1)")
 if m<6.5: level="unlikely"; factors.insert(0,f"Magnitude {m:.1f} is below the ~M6.5 level at which tsunamis are usually generated")
 elif score>=7: level="elevated"
 elif score>=4: level="requires_review"
 else: level="unlikely"
 return TsunamiDetail(level=level,score=score,offshore=offshore,usgs_tsunami_flag=ev.usgs_tsunami_flag,factors=factors)
async def fetch_terrain(lat,lon,radius_km=5.0):
 s=get_settings(); dlat=radius_km/111; dlon=radius_km/(111*max(math.cos(math.radians(lat)),.01)); offsets=[(0,0),(1,0),(-1,0),(0,1),(0,-1),(.707,.707),(.707,-.707),(-.707,.707),(-.707,-.707)]; pts=[]
 for dy,dx in offsets: pts.append((round(max(-90,min(90,lat+dy*dlat)),5),round(((lon+dx*dlon+180)%360)-180,5)))
 try:
  async with httpx.AsyncClient(timeout=s.http_timeout_s,headers={"User-Agent":s.user_agent}) as c:
   r=await c.get(s.elevation_url,params={"latitude":",".join(str(p[0]) for p in pts),"longitude":",".join(str(p[1]) for p in pts)}); r.raise_for_status(); el=[float(x) for x in r.json()["elevation"]]
 except (httpx.HTTPError,KeyError,ValueError,TypeError): return None
 if len(el)!=len(pts): return None
 centre=el[0]; slopes=[math.degrees(math.atan(abs(e-centre)/(radius_km*1000))) for e in el[1:]]
 return TerrainStats(epicenter_elevation_m=round(centre,1),relief_m=round(max(el)-min(el),1),mean_slope_deg=round(sum(slopes)/len(slopes),2),max_slope_deg=round(max(slopes),2),sample_radius_km=radius_km,source="Open-Meteo elevation API (Copernicus DEM ~90 m) - coarse proxy")
def screen_landslide(ev,terrain=None):
 m,d=ev.magnitude,ev.depth_km; factors=[]; basis="magnitude_depth_terrain" if terrain else "magnitude_depth_only"
 if m<5 or d>150:
  why=f"Magnitude {m:.1f} is below ~M5, the usual threshold for earthquake-triggered landslides" if m<5 else f"Focus is very deep ({d:.0f} km), so surface shaking is weak"
  return LandslideDetail(level="low",score=0,basis=basis,factors=[why],terrain=terrain)
 score=0; mp=1 if m<6 else 2 if m<7 else 3 if m<8 else 4; score+=mp; factors.append(f"Magnitude {m:.1f} -> strong shaking potential (+{mp})")
 if d<=15: score+=2; factors.append(f"Very shallow focus ({d:.0f} km) -> intense ground shaking (+2)")
 elif d<=40: score+=1; factors.append(f"Shallow focus ({d:.0f} km) (+1)")
 elif d>70: score-=2; factors.append(f"Deeper focus ({d:.0f} km) reduces surface shaking (-2)")
 if terrain:
  ms=terrain.mean_slope_deg; t=3 if ms>=8 else 2 if ms>=4 else 1 if ms>=1.5 else -1 if ms<.5 else 0; score+=t; factors.append(f"Terrain within ~{terrain.sample_radius_km:.0f} km: mean slope {ms:.1f} deg, relief {terrain.relief_m:.0f} m ({'+' if t>=0 else ''}{t})")
 else: factors.append("No terrain data used (magnitude/depth only)")
 level="high" if score>=6 and m>=6 else "moderate" if score>=3 else "low"
 return LandslideDetail(level=level,score=score,basis=basis,factors=factors,terrain=terrain)
def quick_levels(ev): return screen_tsunami(ev,infer_offshore(ev)).level,screen_landslide(ev,None).level
async def assess(ev,use_terrain=True,include_advisories=True):
 terrain=await fetch_terrain(ev.latitude,ev.longitude) if use_terrain else None; tsunami=screen_tsunami(ev,infer_offshore(ev,terrain)); landslide=screen_landslide(ev,terrain)
 status,advisories=await noaa_service.get_tsunami_advisories() if include_advisories else ("skipped",[])
 real=ev.data_source=="usgs_live"
 return HazardAssessment(event_id=ev.event_id,magnitude=ev.magnitude,depth_km=ev.depth_km,location=ev.location,latitude=ev.latitude,longitude=ev.longitude,timestamp=ev.timestamp,tsunami_screening=tsunami.level,landslide_risk=landslide.level,tsunami=tsunami,landslide=landslide,advisories_status=status,advisories=advisories,advisories_note=noaa_service.COVERAGE_NOTE,preliminary=True,data_source=ev.data_source,data_labels={"earthquake_parameters":"real observation (USGS)" if real else "SIMULATED sample data","tsunami_screening":"preliminary heuristic screening (not an official warning)","landslide_risk":"preliminary heuristic screening"+(" using coarse DEM terrain proxy" if terrain else ""),"advisories":"official NOAA/NWS data (US/Canada coasts only)"},disclaimer=DISCLAIMER)
